@Composable
fun ReportEvidenceScreen(
    amount: Long,
    upiId: String,
    utr: String,
    txnId: String,
    maskPiiOn: Boolean,
    onToggleMask: () -> Unit,
    onConfirmFraudTriggerEmergency: () -> Unit,
    onBack: () -> Unit,
    onSpeakText: (String) -> Unit = {},
    onNavigateToAirGap: () -> Unit = {},
    initialTab: Int = 0,
    modifier: Modifier = Modifier
) {
    var selectedSectionTab by remember { mutableStateOf(initialTab) }
    val scrollState = rememberScrollState()
    var isPackGenerated by remember { mutableStateOf(false) }

    val displayUpi = if (maskPiiOn && upiId.length > 6) {
        "${upiId.take(4)}••••••@${upiId.substringAfter('@')}"
    } else upiId

    if (selectedSectionTab == 1) {
        CommunityScamAwarenessScreen(
            onBack = { selectedSectionTab = 0 },
            onSpeakText = onSpeakText,
            onNavigateToAirGap = onNavigateToAirGap,
            modifier = modifier
        )
        return
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(SatarkBg)
            .verticalScroll(scrollState)
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Top Header
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            IconButton(onClick = onBack, modifier = Modifier.testTag("m7_back_button")) {
                Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back", tint = SatarkInk)
            }
            Text(
                text = "Report preview · not submitted",
                style = MaterialTheme.typography.titleMedium,
                color = SatarkInk,
                fontWeight = FontWeight.Bold
            )
            Spacer(modifier = Modifier.weight(1f))
            TextButton(onClick = onToggleMask) {
                Text(if (maskPiiOn) "👁 Masked ON" else "🔓 Full Raw", color = SatarkAccent, fontSize = 12.sp)
            }
        }

        // Section Tabs: Dossier Pack vs Koo Community
        TabRow(
            selectedTabIndex = selectedSectionTab,
            containerColor = SatarkPanel,
            contentColor = SatarkAccent
        ) {
            Tab(
                selected = selectedSectionTab == 0,
                onClick = { selectedSectionTab = 0 },
                text = { Text("Report Dossier", fontWeight = FontWeight.SemiBold, fontSize = 12.sp) },
                icon = { Icon(Icons.Default.Inventory2, contentDescription = null, modifier = Modifier.size(16.dp)) }
            )
            Tab(
                selected = selectedSectionTab == 1,
                onClick = { selectedSectionTab = 1 },
                text = { Text("Koo Community", fontWeight = FontWeight.SemiBold, fontSize = 12.sp) },
                icon = { Icon(Icons.Default.Groups, contentDescription = null, modifier = Modifier.size(16.dp)) }
            )
        }

        // Evidence Summary Card
        Card(
            shape = RoundedCornerShape(14.dp),
            colors = CardDefaults.cardColors(containerColor = SatarkPanelCard),
            border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(SatarkBorder)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(14.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Text(
                        text = "CURRENT DRAFT · NOT SUBMITTED",
                        style = MaterialTheme.typography.labelSmall,
                        color = SatarkAccent,
                        fontWeight = FontWeight.Bold,
                        letterSpacing = 1.sp
                    )
                    Surface(
                        shape = RoundedCornerShape(4.dp),
                        color = SatarkWarnAlpha
                    ) {
                        Text(
                            text = "USER-REPORTED",
                            fontSize = 9.sp,
                            fontWeight = FontWeight.Bold,
                            color = SatarkWarn,
                            modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                        )
                    }
                }

                Text(
                    text = "Values shown are user-entered only. This preview does not contact a bank, helpline, or reporting portal.",
                    fontSize = 11.sp,
                    color = SatarkDim,
                    lineHeight = 15.sp
                )

                SigRow(label = "Reported disputed amount", value = if (amount > 0L) "₹$amount" else "Not provided", tagText = "User-entered", tagType = SigTagType.INFO)
                SigRow(label = "Additional amount demanded", value = "Not provided", tagText = "Not collected", tagType = SigTagType.INFO)
                SigRow(label = "Suspect beneficiary UPI", value = displayUpi.ifBlank { "Not provided" }, tagText = "User-entered", tagType = SigTagType.INFO)
                SigRow(label = "Bank UTR number", value = utr.ifBlank { "Not provided" }, tagText = "User-entered", tagType = SigTagType.INFO)
                SigRow(label = "UPI transaction ID", value = txnId.ifBlank { "Not provided" }, tagText = "User-entered", tagType = SigTagType.INFO)
                SigRow(label = "Suspect link", value = "Not provided", tagText = "Not collected", tagType = SigTagType.INFO)
                SigRow(label = "File integrity hash", value = "Not generated", tagText = "No export", tagType = SigTagType.INFO)
            }
        }

        // Pack Artifacts Blueprint
        Card(
            shape = RoundedCornerShape(14.dp),
            colors = CardDefaults.cardColors(containerColor = SatarkPanelCard),
            border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(SatarkBorder)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(14.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                Text(
                    text = "EXPORT STATUS",
                    style = MaterialTheme.typography.labelSmall,
                    color = SatarkDim,
                    fontWeight = FontWeight.Bold,
                    letterSpacing = 1.sp
                )

                Text("Report-file export is not implemented. This screen does not create or save a PDF, ZIP, CSV, email, or complaint.", style = MaterialTheme.typography.bodySmall, color = SatarkDim)
            }
        }

        // Community Shortcut Card
        Card(
            shape = RoundedCornerShape(14.dp),
            colors = CardDefaults.cardColors(containerColor = SatarkAccentAlpha),
            border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(SatarkAccent)),
            modifier = Modifier
                .fillMaxWidth()
                .clickable { selectedSectionTab = 1 }
        ) {
            Row(
                modifier = Modifier.padding(14.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Icon(Icons.Default.Groups, contentDescription = null, tint = SatarkAccent, modifier = Modifier.size(24.dp))
                Column(modifier = Modifier.weight(1f)) {
                    Text("Koo Scam Community & Team Chat", fontWeight = FontWeight.Bold, color = SatarkInk, fontSize = 13.5.sp)
                    Text("Discuss latest scams with Prince Kumar Singh, Nishant & Kartik", fontSize = 11.sp, color = SatarkDim)
                }
                Icon(Icons.Default.ChevronRight, contentDescription = null, tint = SatarkAccent)
            }
        }

        // Pack Generation Action
        Button(
            onClick = { isPackGenerated = true },
            modifier = Modifier
                .fillMaxWidth()
                .height(48.dp)
                .testTag("generate_pack_button"),
            colors = ButtonDefaults.buttonColors(containerColor = SatarkAccent),
            shape = RoundedCornerShape(12.dp)
        ) {
            Icon(Icons.Default.Inventory2, contentDescription = null, tint = Color.White)
            Spacer(modifier = Modifier.width(8.dp))
            Text(
                text = if (isPackGenerated) "Preview refreshed · not saved" else "Refresh draft preview · no export",
                color = Color.White,
                style = MaterialTheme.typography.titleSmall,
                fontWeight = FontWeight.Bold
            )
        }

        Divider(color = SatarkBorder)

        // 🚨 CONFIRM FRAUD JUMP TO EMERGENCY
        Card(
            shape = RoundedCornerShape(14.dp),
            colors = CardDefaults.cardColors(containerColor = SatarkDangerAlpha),
            border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(SatarkDanger)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    Icon(Icons.Default.Emergency, contentDescription = null, tint = SatarkDanger)
                    Text(
                        text = "NEED URGENT HELP?",
                        style = MaterialTheme.typography.titleSmall,
                        color = SatarkDanger,
                        fontWeight = FontWeight.Bold
                    )
                }

                Text(
                    text = "This preview is not a complaint. It does not send email, stop a payment, or notify a bank. You can open the 1930 dialer and decide whether to place a call.",
                    style = MaterialTheme.typography.bodyMedium,
                    color = SatarkInk
                )

                Button(
                    onClick = onConfirmFraudTriggerEmergency,
                    colors = ButtonDefaults.buttonColors(containerColor = SatarkDanger),
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(52.dp)
                        .testTag("confirm_fraud_emergency_button"),
                    shape = RoundedCornerShape(12.dp)
                ) {
                    Icon(Icons.Default.Warning, contentDescription = null, tint = Color.White)
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(
                        text = "Open 1930 dialer · no report is sent",
                        color = Color.White,
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold
                    )
                }
            }
        }
    }
}

@Composable
private fun ArtifactRow(title: String, subtitle: String) {
    Column {
        Text(text = title, style = MaterialTheme.typography.bodyMedium, color = SatarkInk, fontWeight = FontWeight.SemiBold)
        Text(text = subtitle, style = MaterialTheme.typography.bodySmall, color = SatarkDim, fontSize = 11.5.sp)
    }
}
