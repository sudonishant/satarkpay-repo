@Composable
fun ReportEvidenceScreen(
    amount: Long,
    upiId: String,
    utr: String,
    txnId: String,
    maskPiiOn: Boolean,
    onToggleMask: () -> Unit,
    onConfirmFraudTriggerEmergency: () -> Unit,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    val scrollState = rememberScrollState()
    var isPackGenerated by remember { mutableStateOf(false) }

    val displayUpi = if (maskPiiOn && upiId.length > 6) {
        "${upiId.take(4)}••••••@${upiId.substringAfter('@')}"
    } else upiId

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(SatarkBg)
            .verticalScroll(scrollState)
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Top Header
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            IconButton(onClick = onBack, modifier = Modifier.testTag("m7_back_button")) {
                Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back", tint = SatarkInk)
            }
            Text(
                text = "M7 · Report & Evidence Pack",
                style = MaterialTheme.typography.titleMedium,
                color = SatarkInk,
                fontWeight = FontWeight.Bold
            )
            Spacer(modifier = Modifier.weight(1f))
            TextButton(onClick = onToggleMask) {
                Text(if (maskPiiOn) "👁 Masked ON" else "🔓 Full Raw", color = SatarkAccent, fontSize = 12.sp)
            }
        }

        // Evidence Summary Card
        Card(
            shape = RoundedCornerShape(14.dp),
            colors = CardDefaults.cardColors(containerColor = SatarkPanelCard),
            border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(SatarkBorder)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(14.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Text(
                        text = "INCIDENT DOSSIER SNAPSHOT",
                        style = MaterialTheme.typography.labelSmall,
                        color = SatarkAccent,
                        fontWeight = FontWeight.Bold,
                        letterSpacing = 1.sp
                    )
                    Surface(
                        shape = RoundedCornerShape(4.dp),
                        color = SatarkWarnAlpha
                    ) {
                        Text(
                            text = "USER-REPORTED",
                            fontSize = 9.sp,
                            fontWeight = FontWeight.Bold,
                            color = SatarkWarn,
                            modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                        )
                    }
                }

                Text(
                    text = "Self-reported incident record for 1930 cyber helpline and bank freeze request. Unverified by bank server.",
                    fontSize = 11.sp,
                    color = SatarkDim,
                    lineHeight = 15.sp
                )

                SigRow(label = "Reported Disputed Amount", value = "₹$amount", tagText = "Self-Reported", tagType = SigTagType.DANGER)
                SigRow(label = "Total Demanded by Suspect", value = "₹30,625", tagText = "3 Demands Logged", tagType = SigTagType.WARN)
                SigRow(label = "Suspect Beneficiary UPI", value = displayUpi, tagText = "Masked for Privacy", tagType = SigTagType.INFO)
                SigRow(label = "Bank UTR Number", value = utr, tagText = "Provided UTR", tagType = SigTagType.OK)
                SigRow(label = "UPI Transaction ID", value = txnId, tagText = "Reported Txn ID", tagType = SigTagType.OK)
                SigRow(label = "Suspect Shortlink", value = "cutt.ly/sec-upi-pay", tagText = "Phishing URL", tagType = SigTagType.WARN)
                SigRow(label = "Local File Integrity Hash", value = "SHA256: 8a3e7b...92e", tagText = "Export Checksum", tagType = SigTagType.INFO)
            }
        }

        // Pack Artifacts Blueprint
        Card(
            shape = RoundedCornerShape(14.dp),
            colors = CardDefaults.cardColors(containerColor = SatarkPanelCard),
            border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(SatarkBorder)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(14.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                Text(
                    text = "DOSSIER ATTACHMENTS (COMPLAINT EXPORT)",
                    style = MaterialTheme.typography.labelSmall,
                    color = SatarkDim,
                    fontWeight = FontWeight.Bold,
                    letterSpacing = 1.sp
                )

                ArtifactRow("📄 complaint_ncrp.md", "National Cyber Crime Reporting Portal ready text in Hindi & English")
                ArtifactRow("📧 complaint_email.eml", "Pre-formatted formal complaint to Cyber Cell & Bank Nodal Officer")
                ArtifactRow("📊 annexure.csv", "Detailed transaction timeline with hashes & suspect handles")
                ArtifactRow("📦 evidence_bundle.zip", "Tamper-evident ZIP archive with digital signatures & OCR proofs")
            }
        }

        // Pack Generation Action
        Button(
            onClick = { isPackGenerated = true },
            modifier = Modifier
                .fillMaxWidth()
                .height(48.dp)
                .testTag("generate_pack_button"),
            colors = ButtonDefaults.buttonColors(containerColor = SatarkAccent),
            shape = RoundedCornerShape(12.dp)
        ) {
            Icon(Icons.Default.Inventory2, contentDescription = null, tint = Color.White)
            Spacer(modifier = Modifier.width(8.dp))
            Text(
                text = if (isPackGenerated) "📦 Pack Ready (Saved Locally)" else "📦 Pack Banao (8 Seconds)",
                color = Color.White,
                style = MaterialTheme.typography.titleSmall,
                fontWeight = FontWeight.Bold
            )
        }

        Divider(color = SatarkBorder)

        // 🚨 CONFIRM FRAUD JUMP TO EMERGENCY
        Card(
            shape = RoundedCornerShape(14.dp),
            colors = CardDefaults.cardColors(containerColor = SatarkDangerAlpha),
            border = CardDefaults.outlinedCardBorder().copy(brush = androidx.compose.ui.graphics.SolidColor(SatarkDanger)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    Icon(Icons.Default.Emergency, contentDescription = null, tint = SatarkDanger)
                    Text(
                        text = "PAISA KAT GAYA HAI? (FRAUD CONFIRMED)",
                        style = MaterialTheme.typography.titleSmall,
                        color = SatarkDanger,
                        fontWeight = FontWeight.Bold
                    )
                }

                Text(
                    text = "Agar lagta hai fraud ho gaya hai, aur aap confirm karte hain — to turant Cyber Cell ko complaint mail bhejein aur helpline se payment stop karein.",
                    style = MaterialTheme.typography.bodyMedium,
                    color = SatarkInk
                )

                Button(
                    onClick = onConfirmFraudTriggerEmergency,
                    colors = ButtonDefaults.buttonColors(containerColor = SatarkDanger),
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(52.dp)
                        .testTag("confirm_fraud_emergency_button"),
                    shape = RoundedCornerShape(12.dp)
                ) {
                    Icon(Icons.Default.Warning, contentDescription = null, tint = Color.White)
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(
                        text = "🚨 FRAUD CONFIRM → S9 Emergency Chalu Karo",
                        color = Color.White,
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold
                    )
                }
            }
        }
    }
}

@Composable
private fun ArtifactRow(title: String, subtitle: String) {
    Column {
        Text(text = title, style = MaterialTheme.typography.bodyMedium, color = SatarkInk, fontWeight = FontWeight.SemiBold)
        Text(text = subtitle, style = MaterialTheme.typography.bodySmall, color = SatarkDim, fontSize = 11.5.sp)
    }
}
