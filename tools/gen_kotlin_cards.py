"""Regenerate PlaybookCards.kt from thehro/playbooks.json (single source of truth)."""
import json
from pathlib import Path
R = Path(__file__).resolve().parents[1]
d = json.loads((R / "thehro/playbooks.json").read_text())
q = lambda s: json.dumps(s, ensure_ascii=False)
rows = []
for c in d["cards"]:
    st = ", ".join(q(x) for x in c["stages"])
    fl = q(c["tier_floor"]) if c["tier_floor"] else "null"
    rows.append(f'        PlaybookCard({q(c["id"])}, {q(c["name"])}, listOf({st}), {c["min_match"]}, {q(c["anchor"])}, {fl},\n'
                f'            {q(c["reason"])},\n            {q(c["question"])})')
kt = f'''package com.example.thehro

// GENERATED by tools/gen_kotlin_cards.py from thehro/playbooks.json ({d["version"]}). Do not edit by hand.
// In production, cards arrive over the air, Ed25519-signed, and replace this default set.

data class PlaybookCard(
    val id: String,
    val name: String,
    val stages: List<String>,
    val minMatch: Int,
    val anchor: String,
    val tierFloor: String?,
    val reason: String,
    val question: String,
)

object PlaybookCards {{
    const val VERSION = "{d["version"]}"
    val P1: List<PlaybookCard> = listOf(
{",\n".join(rows)}
    )
}}
'''
out = R / "app/satarkpay-android/app/src/main/java/com/example/thehro/PlaybookCards.kt"
out.write_text(kt); print("wrote", out)
